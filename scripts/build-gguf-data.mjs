#!/usr/bin/env node
// Generates lib/gguf.ts from the OpenGrad repository at the frozen `study-001`
// tag (results/quantization/gguf), so the /gguf page never retypes a number.
//
//   OPENGRAD=../OpenGrad node scripts/build-gguf-data.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OPENGRAD = resolve(process.env.OPENGRAD ?? "../OpenGrad");
const TAG = "study-001";
const DIR = "results/quantization/gguf";

const read = (path) =>
  JSON.parse(execFileSync("git", ["-C", OPENGRAD, "show", `${TAG}:${path}`], { encoding: "utf8", maxBuffer: 1 << 28 }));
const round = (x, d) => Math.round(x * 10 ** d) / 10 ** d;

function bench(format) {
  const rows = read(`${DIR}/bench_m1-v2-${format}.json`).rows;
  const pick = (p, g) => rows.find((r) => r.n_prompt === p && r.n_gen === g);
  return { pp: pick(2048, 0), tg: pick(0, 128) };
}

const verdict = read(`${DIR}/ladder_verdict.json`);
const bf16Score = read(`${DIR}/score_m1-v2-bf16_confirmatory.json`);
const base = bench("bf16");
const params = base.tg.model_n_params;

const entry = (format, bytes, agreement, passes) => {
  const { pp, tg } = bench(format === "BF16" ? "bf16" : format);
  return {
    format,
    bytes,
    gib: round(bytes / 2 ** 30, 2),
    bitsPerWeight: round((bytes * 8) / params, 2),
    tg: round(tg.avg_ts, 1),
    tgSd: round(tg.stddev_ts, 1),
    pp: Math.round(pp.avg_ts),
    ppSd: Math.round(pp.stddev_ts),
    agreement,
    passes,
  };
};

const rows = [
  entry("BF16", bf16Score.artifact_bytes, null, bf16Score.gate_vs_frozen_vllm_reference.decision === "PTQ_ACCEPTED"),
  ...verdict.rungs.map((r) => entry(r.rung, r.artifact_bytes, round(r.decision_agreement, 4), r.gate.decision === "PTQ_ACCEPTED")),
];

const pp512 = ["bf16", ...verdict.rungs.map((r) => r.rung)].map((f) => {
  const row = read(`${DIR}/bench_m1-v2-${f}.json`).rows.find((r) => r.n_prompt === 512 && r.n_gen === 0);
  return row.stddev_ts / row.avg_ts;
});

const conditions = {
  pp512MaxRelSd: round(Math.max(...pp512), 3),
  engine: `llama.cpp ${base.tg.build_commit}, ${base.tg.backends} backend, llama-bench`,
  gpu: base.tg.gpu_info,
  params,
  offload: base.tg.n_gpu_layers >= 999 ? "all layers on the GPU" : `${base.tg.n_gpu_layers} layers on the GPU`,
  batch: `${base.tg.n_batch} batch, ${base.tg.n_ubatch} micro-batch, ${base.tg.n_threads} CPU threads`,
  kvCache: `${base.tg.type_k} keys, ${base.tg.type_v} values`,
  repetitions: base.tg.samples_ts.length,
  runDate: base.tg.test_time.slice(0, 10),
  examples: bf16Score.records,
};

const header = `// GENERATED by scripts/build-gguf-data.mjs from github.com/arjhinety/OpenGrad at
// tag ${TAG} (${DIR}). Do not edit by hand; re-run the script.
// The M1-v2 checkpoint (Qwen3.5-2B, OpenGrad Study 001) as BF16 GGUF and nine
// imatrix quantizations. Throughput is llama-bench: pp = prompt processing at
// 2,048 tokens, tg = generation of 128 tokens, tokens per second, mean and
// standard deviation over the repetitions. Agreement is the share of the
// confirmatory examples where the format made the same tool-use decision as
// the BF16 GGUF.
`;

const body = [
  `export const ggufLinks = ${JSON.stringify({
    report: `https://github.com/arjhinety/OpenGrad/blob/${TAG}/reports/QUANTIZATION_PTQ_EVALUATION.md`,
    results: `https://github.com/arjhinety/OpenGrad/tree/${TAG}/${DIR}`,
    errata: `https://github.com/arjhinety/OpenGrad/blob/${TAG}/reports/ERRATA.md`,
    study: "https://opengrad.arjhinety.com/studies/001#quantization",
    model: "https://huggingface.co/arrochi112/OpenGrad-Qwen3.5-2B-M1-DPO-CanonicalV2-Final-v2",
  }, null, 2)};`,
  `export const ggufConditions = ${JSON.stringify(conditions, null, 2)};`,
  `export const ggufRecommended = ${JSON.stringify(verdict.selection.recommended_release_rung)};`,
  `export type GgufRow = {\n  format: string;\n  bytes: number;\n  gib: number;\n  bitsPerWeight: number;\n  tg: number;\n  tgSd: number;\n  pp: number;\n  ppSd: number;\n  agreement: number | null;\n  passes: boolean;\n};`,
  `export const ggufRows: GgufRow[] = ${JSON.stringify(rows, null, 2)};`,
].join("\n\n");

writeFileSync(resolve("lib/gguf.ts"), `${header}\n${body}\n`);
console.log(`wrote lib/gguf.ts: ${rows.length} formats from ${TAG}`);
