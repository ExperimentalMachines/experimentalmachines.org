#!/usr/bin/env node
// Generates lib/execupack-published.ts from the Hugging Face API: every
// experimentalmachines/<model>-ExecuTorch repo execupack has published, and the
// .pte files in each backend folder, so the /executorch page never retypes a
// file list.
//
//   node scripts/build-execupack-data.mjs
//
// Needs network access only; HF_TOKEN is used if set but nothing here is gated.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const ORG = "experimentalmachines";
const SUFFIX = "-ExecuTorch";
const API = "https://huggingface.co/api";
const headers = process.env.HF_TOKEN ? { Authorization: `Bearer ${process.env.HF_TOKEN}` } : {};

const get = async (path) => {
  const res = await fetch(`${API}${path}`, { headers });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
};

// Repo name (without the suffix) -> family key in lib/execupack.ts. A repo that
// matches none stops the script, so a new family is added on purpose, not dropped.
const FAMILY_RULES = [
  [/^Qwen3\.5-/, "qwen3_5"],
  [/^Qwen3-/, "qwen3"],
  [/^Qwen2\.5-/, "qwen2_5"],
  [/^Llama-3\.2-/, "llama3_2"],
  [/^SmolLM2-/, "smollm2"],
  [/^SmolLM3-/, "smollm3"],
  [/^LFM2/, "lfm2"],
  [/^gemma-3-/i, "gemma3"],
  [/^gemma-2-/i, "gemma2"],
  [/^Phi-4-mini/i, "phi4_mini"],
];

const BACKENDS = new Set(["xnnpack", "vulkan", "qnn", "mtk"]);

// "2k" -> 2048, "512" -> 512 (execupack's naming.window_token).
const windowTokens = (token) => (token.endsWith("k") ? Number(token.slice(0, -1)) * 1024 : Number(token));

// execupack file names (pipeline/naming.py):
//   xnnpack/<name>-8da4w[-gptq]-<w>.pte, or <name>-fp32-<w>.pte (linears unquantized)
//   vulkan/<name>-vulkan-8da4w-<w>.pte
//   qnn/<soc>/<name>-...-<w>.pte
//   mtk/<soc>/<name>-neuropilot-<a16w4>-<w>-chunk<i>of<n>.pte
function parse(path) {
  const parts = path.split("/");
  const backend = parts[0];
  if (!BACKENDS.has(backend) || !path.endsWith(".pte")) return null;
  const chip = backend === "qnn" || backend === "mtk" ? parts[1].toUpperCase() : null;
  const file = parts.at(-1);
  const w = file.match(/-(\d+k|\d{3,5})(?:-chunk\d+of\d+)?\.pte$/);
  if (!w) throw new Error(`no window in ${path}`);
  let recipe;
  if (backend === "mtk") recipe = file.match(/-neuropilot-(a\d+w\d+)-/i)?.[1].toUpperCase() ?? "NeuroPilot";
  else if (backend === "qnn") recipe = "QNN HTP";
  else if (/-fp32-/.test(file)) recipe = "fp32 linears";
  else recipe = /-gptq-/.test(file) ? "8da4w GPTQ" : "8da4w";
  return { backend, chip, recipe, window: windowTokens(w[1]) };
}

const listing = await get(`/models?author=${ORG}&limit=1000`);
const ids = listing.map((m) => m.id).filter((id) => id.endsWith(SUFFIX)).sort((a, b) => a.localeCompare(b));

const repos = [];
for (const id of ids) {
  const info = await get(`/models/${id}`);
  const name = id.slice(ORG.length + 1, -SUFFIX.length);
  const family = FAMILY_RULES.find(([re]) => re.test(name))?.[1];
  if (!family) throw new Error(`${id}: no family rule matches ${name}; add one to FAMILY_RULES`);
  const groups = new Map();
  for (const s of info.siblings ?? []) {
    const f = parse(s.rfilename);
    if (!f) continue;
    const key = `${f.backend}|${f.chip ?? ""}|${f.recipe}`;
    if (!groups.has(key)) groups.set(key, { backend: f.backend, chip: f.chip, recipe: f.recipe, windows: new Set() });
    groups.get(key).windows.add(f.window);
  }
  const base = info.cardData?.base_model;
  repos.push({
    id,
    name,
    family,
    source: Array.isArray(base) ? base[0] : (base ?? null),
    sha: info.sha,
    lastModified: info.lastModified.slice(0, 10),
    builds: [...groups.values()]
      .map((g) => ({ ...g, windows: [...g.windows].sort((a, b) => a - b) }))
      .sort((a, b) => a.backend.localeCompare(b.backend) || (a.chip ?? "").localeCompare(b.chip ?? "")),
  });
}

const asOf = repos.map((r) => r.lastModified).sort().at(-1);

const out = `// GENERATED by scripts/build-execupack-data.mjs from the Hugging Face API
// (huggingface.co/${ORG}, every *${SUFFIX} repo). Do not edit by hand; re-run the script.
// One entry per published repo; builds group its .pte files by backend folder,
// chip and recipe, with the context windows (tokens) present.

export type PublishedBuild = {
  backend: "xnnpack" | "vulkan" | "qnn" | "mtk";
  chip: string | null;
  recipe: string;
  windows: number[];
};

export type PublishedRepo = {
  id: string;
  name: string;
  family: string;
  source: string | null;
  sha: string;
  lastModified: string;
  builds: PublishedBuild[];
};

export const publishedAsOf = ${JSON.stringify(asOf)};

export const publishedRepos: PublishedRepo[] = ${JSON.stringify(repos, null, 2)};
`;

const target = resolve(import.meta.dirname, "../lib/execupack-published.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${repos.length} repos, newest change ${asOf}`);
